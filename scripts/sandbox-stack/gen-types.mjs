#!/usr/bin/env node
// Generates src/lib/supabase/database.types.ts from the live database catalog, in
// the same shape as `supabase gen types typescript` (Tables, Views, Functions with
// Row / Insert / Update / Relationships). Used where the Supabase CLI's Docker-based
// generator is unavailable. Usage: node scripts/sandbox-stack/gen-types.mjs [--check]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DB_URL = process.env.DATABASE_URL ?? "postgres://postgres:postgres@127.0.0.1:54322/postgres";
const OUT = join(process.cwd(), "src/lib/supabase/database.types.ts");

const query = String.raw`
with cols as (
  select c.table_name, c.column_name, c.ordinal_position, c.is_nullable = 'YES' as nullable,
         c.column_default is not null or c.is_identity = 'YES' as has_default,
         c.is_identity = 'YES' and c.identity_generation = 'ALWAYS' as always_identity,
         c.data_type, c.udt_name
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE' and c.table_name <> 'sandbox_migrations'
),
fks as (
  select con.conname, rel.relname as table_name, frel.relname as ref_table,
         array(select a.attname from unnest(con.conkey) with ordinality k(n, o) join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.o) as cols,
         array(select a.attname from unnest(con.confkey) with ordinality k(n, o) join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.o) as ref_cols
  from pg_constraint con
  join pg_class rel on rel.oid = con.conrelid
  join pg_class frel on frel.oid = con.confrelid
  join pg_namespace n on n.oid = rel.relnamespace
  join pg_namespace fn on fn.oid = frel.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
),
funcs as (
  select p.proname, pg_get_function_identity_arguments(p.oid) as identity,
         coalesce(p.proargnames, '{}') as argnames, p.proargtypes::oid[] as argtypes,
         p.pronargdefaults as ndefaults, p.proretset as retset,
         pg_get_function_result(p.oid) as result, format_type(p.prorettype, null) as rettype
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and has_function_privilege('authenticated', p.oid, 'execute')
    and p.proname not in ('require_user', 'quiz_options_valid')
)
select json_build_object(
  'columns', (select json_agg(cols order by table_name, ordinal_position) from cols),
  'fks', (select coalesce(json_agg(fks order by table_name, conname), '[]') from fks),
  'funcs', (select coalesce(json_agg(json_build_object(
      'name', proname, 'argnames', argnames, 'ndefaults', ndefaults, 'retset', retset, 'result', result, 'rettype', rettype,
      'argtypes', (select json_agg(format_type(t, null) order by o) from unnest(argtypes) with ordinality u(t, o))
    ) order by proname), '[]') from funcs)
);`;

const raw = execFileSync("psql", [DB_URL, "-tAc", query], { encoding: "utf8" });
const { columns, fks, funcs } = JSON.parse(raw);

const scalar = (pgType) => {
  const t = pgType.replace(/^_/, "").replace(/\[\]$/, "");
  if (
    [
      "int2",
      "int4",
      "int8",
      "smallint",
      "integer",
      "bigint",
      "numeric",
      "float4",
      "float8",
      "real",
      "double precision",
    ].includes(t)
  )
    return "number";
  if (["bool", "boolean"].includes(t)) return "boolean";
  if (["json", "jsonb"].includes(t)) return "Json";
  return "string";
};
const tsColumn = (c) => (c.data_type === "ARRAY" ? `${scalar(c.udt_name)}[]` : scalar(c.udt_name));
const tsFormatType = (t) => (t.endsWith("[]") ? `${scalar(t.slice(0, -2))}[]` : scalar(t));

const tables = {};
for (const c of columns) (tables[c.table_name] ??= []).push(c);

const lines = [];
const out = (s = "") => lines.push(s);
out(
  "// Generated by scripts/sandbox-stack/gen-types.mjs from the database schema. Do not edit by hand.",
);
out(
  "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];",
);
out();
out("export type Database = {");
out('  __InternalSupabase: { PostgrestVersion: "13" };');
out("  public: {");
out("    Tables: {");
for (const [name, cols] of Object.entries(tables)) {
  out(`      ${name}: {`);
  out("        Row: {");
  for (const c of cols)
    out(`          ${c.column_name}: ${tsColumn(c)}${c.nullable ? " | null" : ""};`);
  out("        };");
  out("        Insert: {");
  for (const c of cols) {
    const t = `${tsColumn(c)}${c.nullable ? " | null" : ""}`;
    if (c.always_identity) out(`          ${c.column_name}?: never;`);
    else out(`          ${c.column_name}${c.nullable || c.has_default ? "?" : ""}: ${t};`);
  }
  out("        };");
  out("        Update: {");
  for (const c of cols) {
    if (c.always_identity) out(`          ${c.column_name}?: never;`);
    else out(`          ${c.column_name}?: ${tsColumn(c)}${c.nullable ? " | null" : ""};`);
  }
  out("        };");
  out("        Relationships: [");
  for (const fk of fks.filter((f) => f.table_name === name)) {
    out("          {");
    out(`            foreignKeyName: "${fk.conname}";`);
    out(`            columns: [${fk.cols.map((x) => `"${x}"`).join(", ")}];`);
    out("            isOneToOne: false;");
    out(`            referencedRelation: "${fk.ref_table}";`);
    out(`            referencedColumns: [${fk.ref_cols.map((x) => `"${x}"`).join(", ")}];`);
    out("          },");
  }
  out("        ];");
  out("      };");
}
out("    };");
out("    Views: { [_ in never]: never };");
out("    Functions: {");
for (const f of funcs) {
  const names = f.argnames;
  const types = f.argtypes ?? [];
  const firstDefault = types.length - f.ndefaults;
  const args = types.length
    ? `{ ${types.map((t, i) => `${names[i]}${i >= firstDefault ? "?" : ""}: ${tsFormatType(t)}`).join("; ")} }`
    : "never";
  let returns;
  if (f.result.startsWith("TABLE(")) {
    const inner = f.result
      .slice(6, -1)
      .split(/,\s*/)
      .map((part) => {
        const [col, ...type] = part.split(" ");
        return `${col}: ${tsFormatType(type.join(" ").replace("timestamp with time zone", "timestamptz"))}`;
      });
    returns = `{ ${inner.join("; ")} }[]`;
  } else if (f.rettype === "void") returns = "undefined";
  else returns = tsFormatType(f.rettype.replace("timestamp with time zone", "timestamptz"));
  out(`      ${f.name}: { Args: ${args}; Returns: ${returns} };`);
}
out("    };");
out("    Enums: { [_ in never]: never };");
out("    CompositeTypes: { [_ in never]: never };");
out("  };");
out("};");
out();
out('type PublicSchema = Database["public"];');
out(
  'export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];',
);
out(
  'export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];',
);
out(
  'export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];',
);

const content = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== content) {
    console.error(
      "database.types.ts is out of date. Run: node scripts/sandbox-stack/gen-types.mjs",
    );
    process.exit(1);
  }
  console.log("database.types.ts is up to date.");
} else {
  writeFileSync(OUT, content);
  console.log(`Wrote ${OUT}`);
}
