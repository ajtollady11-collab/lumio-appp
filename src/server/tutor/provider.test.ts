import Anthropic from "@anthropic-ai/sdk";
import { describe, expect, it, vi } from "vitest";

import {
  AnthropicTutorProvider,
  classifyProviderError,
  TestTutorProvider,
  TUTOR_MAX_OUTPUT_TOKENS,
  TutorProviderError,
} from "./provider";

function fakeClient(events: unknown[], final: unknown, failAfter?: number) {
  const stream = vi.fn(() => ({
    async *[Symbol.asyncIterator]() {
      for (let i = 0; i < events.length; i++) {
        if (failAfter !== undefined && i === failAfter)
          throw new Anthropic.RateLimitError(429, undefined, "slow down", new Headers());
        yield events[i];
      }
    },
    finalMessage: async () => final,
  }));
  return { client: { messages: { stream } } as unknown as Pick<Anthropic, "messages">, stream };
}

const delta = (text: string) => ({
  type: "content_block_delta",
  index: 0,
  delta: { type: "text_delta", text },
});

async function collect(iterable: AsyncIterable<string>) {
  let out = "";
  for await (const chunk of iterable) out += chunk;
  return out;
}

describe("AnthropicTutorProvider", () => {
  it("sends the model, output limit, cached system prompt and messages", async () => {
    const { client, stream } = fakeClient([delta("Hello"), delta(" there")], {
      model: "claude-sonnet-5-5",
      usage: {
        input_tokens: 10,
        output_tokens: 4,
        cache_read_input_tokens: 90,
        cache_creation_input_tokens: 0,
      },
    });
    const provider = new AnthropicTutorProvider("claude-sonnet-5-5", client);
    const signal = new AbortController().signal;
    const result = provider.stream({
      system: "SYSTEM",
      messages: [{ role: "user", content: "Hi" }],
      signal,
    });

    expect(await collect(result.text)).toBe("Hello there");
    expect(await result.usage()).toEqual({
      model: "claude-sonnet-5-5",
      inputTokens: 100,
      outputTokens: 4,
    });
    expect(stream).toHaveBeenCalledWith(
      {
        model: "claude-sonnet-5-5",
        max_tokens: TUTOR_MAX_OUTPUT_TOKENS,
        system: [{ type: "text", text: "SYSTEM", cache_control: { type: "ephemeral" } }],
        messages: [{ role: "user", content: "Hi" }],
      },
      { signal },
    );
  });

  it("ignores non-text events", async () => {
    const { client } = fakeClient(
      [
        { type: "message_start" },
        delta("A"),
        { type: "content_block_delta", delta: { type: "input_json_delta" } },
      ],
      { usage: { input_tokens: 1, output_tokens: 1 } },
    );
    const result = new AnthropicTutorProvider("m", client).stream({
      system: "",
      messages: [],
      signal: new AbortController().signal,
    });
    expect(await collect(result.text)).toBe("A");
  });

  it("converts SDK errors mid-stream into a classified error", async () => {
    const { client } = fakeClient([delta("A"), delta("B")], {}, 1);
    const result = new AnthropicTutorProvider("m", client).stream({
      system: "",
      messages: [],
      signal: new AbortController().signal,
    });
    await expect(collect(result.text)).rejects.toMatchObject({ code: "ai_busy" });
  });
});

describe("classifyProviderError", () => {
  const headers = new Headers();
  it.each([
    [new Anthropic.AuthenticationError(401, undefined, "bad key", headers), "ai_auth_failed"],
    [new Anthropic.RateLimitError(429, undefined, "slow", headers), "ai_busy"],
    [new Anthropic.InternalServerError(500, undefined, "oops", headers), "ai_unavailable"],
    [new Anthropic.APIConnectionTimeoutError(), "ai_timeout"],
    [Object.assign(new Error("aborted"), { name: "AbortError" }), "ai_timeout"],
    [new Error("something else"), "ai_error"],
  ])("classifies %s", (error, code) => {
    expect(classifyProviderError(error).code).toBe(code);
  });

  it("passes through an already-classified error", () => {
    const error = new TutorProviderError("ai_busy", "x");
    expect(classifyProviderError(error)).toBe(error);
  });
});

describe("TestTutorProvider", () => {
  it("labels its replies as not generated by AI", async () => {
    const result = new TestTutorProvider().stream({
      system: "",
      messages: [{ role: "user", content: "What is 2 + 2?" }],
      signal: new AbortController().signal,
    });
    const text = await collect(result.text);
    expect(text).toContain("Test response — not generated by AI");
    expect(text).toContain("What is 2 + 2?");
  });

  it("can simulate a provider failure", async () => {
    const result = new TestTutorProvider().stream({
      system: "",
      messages: [{ role: "user", content: "[test:fail] hello" }],
      signal: new AbortController().signal,
    });
    await expect(collect(result.text)).rejects.toMatchObject({ code: "ai_unavailable" });
  });
});
