import "server-only";

import Anthropic from "@anthropic-ai/sdk";

import type { ChatMessage } from "./prompt";
import { brand } from "@/lib/brand";

export type TutorUsage = { inputTokens: number; outputTokens: number; model: string };

export type TutorStream = {
  /** Text fragments as they arrive. */
  text: AsyncIterable<string>;
  /** Resolves once the reply is complete (after `text` is exhausted). */
  usage: () => Promise<TutorUsage>;
};

export interface TutorProvider {
  readonly name: "anthropic" | "test";
  stream(input: { system: string; messages: ChatMessage[]; signal: AbortSignal }): TutorStream;
}

export type TutorErrorCode =
  "ai_auth_failed" | "ai_busy" | "ai_timeout" | "ai_unavailable" | "ai_error";

export class TutorProviderError extends Error {
  constructor(
    public readonly code: TutorErrorCode,
    message: string,
  ) {
    super(message);
    this.name = "TutorProviderError";
  }
}

/** Maps SDK errors to a small set of causes the UI can explain. */
export function classifyProviderError(error: unknown): TutorProviderError {
  if (error instanceof TutorProviderError) return error;
  if (
    error instanceof Anthropic.AuthenticationError ||
    error instanceof Anthropic.PermissionDeniedError
  ) {
    return new TutorProviderError(
      "ai_auth_failed",
      `The AI provider rejected ${brand.name}'s credentials.`,
    );
  }
  if (error instanceof Anthropic.RateLimitError) {
    return new TutorProviderError("ai_busy", "The AI provider is rate limiting requests.");
  }
  if (
    error instanceof Anthropic.APIConnectionTimeoutError ||
    error instanceof Anthropic.APIUserAbortError ||
    (error instanceof Error && error.name === "AbortError")
  ) {
    return new TutorProviderError("ai_timeout", "The AI provider took too long to respond.");
  }
  if (
    error instanceof Anthropic.APIConnectionError ||
    error instanceof Anthropic.InternalServerError
  ) {
    return new TutorProviderError("ai_unavailable", "The AI provider is unavailable.");
  }
  if (error instanceof Anthropic.APIError && error.status === 529) {
    return new TutorProviderError("ai_unavailable", "The AI provider is overloaded.");
  }
  return new TutorProviderError("ai_error", "The AI provider returned an unexpected error.");
}

type MessagesClient = Pick<Anthropic, "messages">;

export const TUTOR_MAX_OUTPUT_TOKENS = 1500;

/** Claude via the official SDK. The client is injectable for tests. */
export class AnthropicTutorProvider implements TutorProvider {
  readonly name = "anthropic" as const;

  constructor(
    private readonly model: string,
    private readonly client: MessagesClient,
  ) {}

  stream({
    system,
    messages,
    signal,
  }: {
    system: string;
    messages: ChatMessage[];
    signal: AbortSignal;
  }): TutorStream {
    const stream = this.client.messages.stream(
      {
        model: this.model,
        max_tokens: TUTOR_MAX_OUTPUT_TOKENS,
        // The behaviour prompt is identical across turns, so cache it.
        system: [{ type: "text", text: system, cache_control: { type: "ephemeral" } }],
        messages: messages.map((m) => ({ role: m.role, content: m.content })),
      },
      { signal },
    );

    const model = this.model;
    async function* text() {
      try {
        for await (const event of stream) {
          if (event.type === "content_block_delta" && event.delta.type === "text_delta") {
            yield event.delta.text;
          }
        }
      } catch (error) {
        throw classifyProviderError(error);
      }
    }

    return {
      text: text(),
      usage: async () => {
        try {
          const final = await stream.finalMessage();
          return {
            model: final.model ?? model,
            inputTokens:
              final.usage.input_tokens +
              (final.usage.cache_read_input_tokens ?? 0) +
              (final.usage.cache_creation_input_tokens ?? 0),
            outputTokens: final.usage.output_tokens,
          };
        } catch (error) {
          throw classifyProviderError(error);
        }
      },
    };
  }
}

/**
 * Deterministic provider for automated tests and local development without an API
 * key. Its replies say plainly that they are not AI-generated. The environment
 * schema refuses to enable it in production.
 */
export class TestTutorProvider implements TutorProvider {
  readonly name = "test" as const;

  stream({
    messages,
    signal,
  }: {
    system: string;
    messages: ChatMessage[];
    signal: AbortSignal;
  }): TutorStream {
    const question = messages.at(-1)?.content ?? "";
    const shouldFail = question.includes("[test:fail]");
    const reply = `**Test response — not generated by AI.** ${brand.name}'s test provider is active, so no AI model was called.\n\nYou asked: "${question.slice(0, 200)}"\n\n1. This reply is fixed text used by automated tests.\n2. Configure \`ANTHROPIC_API_KEY\` to get real tutoring.\n\nInline maths renders like $a^2 + b^2 = c^2$.`;
    const words = reply.split(/(?<=\s)/);

    async function* text() {
      for (let i = 0; i < words.length; i++) {
        if (signal.aborted) throw new TutorProviderError("ai_timeout", "Request cancelled.");
        if (shouldFail && i === 3)
          throw new TutorProviderError("ai_unavailable", "Simulated provider failure.");
        await new Promise((r) => setTimeout(r, 4));
        yield words[i]!;
      }
    }
    return {
      text: text(),
      usage: async () => ({ model: "lumio-test-provider", inputTokens: 0, outputTokens: 0 }),
    };
  }
}
