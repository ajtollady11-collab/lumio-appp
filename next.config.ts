import type { NextConfig } from "next";

import { validateEnv } from "./src/lib/env/schema";

// Fail the build (and `next dev`) immediately if required configuration is missing
// or malformed, instead of failing at request time in production.
validateEnv(process.env);

/**
 * Baseline security headers for every response.
 * A nonce-based Content-Security-Policy is added in M1c together with auth,
 * once the app loads third-party scripts it needs to allow-list.
 */
const securityHeaders = [
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
  },
];

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  reactStrictMode: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
